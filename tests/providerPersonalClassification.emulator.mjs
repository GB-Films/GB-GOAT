import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../functions/package.json', import.meta.url));
const admin = require('firebase-admin');
const { classifyPersonalProvider, preserved } = require('../functions/providerPersonalClassification');
const { createProviderPortalHandler } = require('../functions/providerPortal');
if (!/^127\.0\.0\.1:\d+$/.test(process.env.FIRESTORE_EMULATOR_HOST || '')) throw Error('Local Firestore emulator required; production forbidden.');
const app = admin.initializeApp({ projectId: 'demo-goat-person-classification' }, 'personal-classification-test');
const db = app.firestore(), timestamp = () => admin.firestore.FieldValue.serverTimestamp();
const input = { operationKey: 'fictitious-classification-operation', providerId: 'legacy', targetUid: 'own', targetEmail: 'own@example.test', operatorUid: 'admin', operatorEmail: 'admin@example.test',
  confirmedPersonal: true, reason: 'Autorización ficticia para corregir sólo clasificación.', authorizationSha256: 'f'.repeat(64) };
const accounts = Object.fromEntries(['own', 'admin'].map(uid => [uid, { uid, email: `${uid}@example.test`, emailVerified: true, disabled: false, providerData: [{ providerId: 'google.com' }] }]));
const findAccountByUid = async uid => accounts[uid];
const run = (patch = {}, apply = false) => classifyPersonalProvider({ db, input: { ...input, ...patch }, operatorEmail: input.operatorEmail, findAccountByUid, timestamp, apply });
try {
  const provider = { name: 'Persona ficticia', source: 'manual', bankAccount_cbu: 'legacy-invalid-bank', bankAccount_alias: '', notes: 'Conservar todos los campos', createdAt: admin.firestore.Timestamp.fromMillis(1) };
  const membership = { providerId: 'legacy', email: 'own@example.test', status: 'needs_confirmation', assignedBy: { uid: 'admin' } };
  const work = { providerId: 'legacy', providerName: provider.name, area: 'Arte', total: 100, paymentHistory: [{ id: 'payment', amount: 25, createdBy: 'another' }] };
  await db.doc('users/admin').set({ uid: 'admin', role: 'admin', email: 'admin@example.test' });
  await db.doc('providers/legacy').set(provider);
  await db.doc('providerPortalUsers/own/memberships/legacy').set(membership);
  await db.doc('projects/film').set({ name: 'Proyecto ficticio', activeAreas: ['Arte'] });
  await db.doc('projects/film/areaExpenses/work').set(work);
  const original = (await db.doc('providers/legacy').get()).data();
  const preview = await run();
  assert.equal(preview.outcome, 'preview'); assert.deepEqual((await db.doc('providers/legacy').get()).data(), original);
  assert.equal((await db.collection('providerPortalAudit').get()).size, 0);
  await assert.rejects(run({ ...input, targetUid: 'foreign' }), /cuenta Google/);
  await assert.rejects(run({ expectedVersion: '1.000000000', expectedPreservationHash: preview.expectedPreservationHash }, true), /versión/);
  const command = { expectedVersion: preview.expectedVersion, expectedPreservationHash: preview.expectedPreservationHash };
  const results = await Promise.all([run(command, true), run(command, true)]);
  assert.deepEqual(results.map(result => result.outcome).sort(), ['already_applied', 'applied']);
  assert.equal(results.find(result => result.outcome === 'applied').verification, 'passed');
  assert.equal((await db.collection('providerPortalAudit').get()).size, 1);
  const corrected = (await db.doc('providers/legacy').get()).data();
  assert.equal(corrected.type, 'persona'); assert.deepEqual(preserved(corrected), preserved(original));
  assert.deepEqual((await db.doc('projects/film/areaExpenses/work').get()).data(), work);
  assert.deepEqual((await db.doc('providerPortalUsers/own/memberships/legacy').get()).data(), membership);
  assert.equal((await db.doc('users/own').get()).exists, false);
  const portal = createProviderPortalHandler({ db, timestamp, findAccountByUid, sign: { list: async () => [] } });
  const call = data => portal({ auth: { uid: 'own', token: { email: 'own@example.test', email_verified: true, firebase: { sign_in_provider: 'google.com' } } }, data });
  await db.doc('providerPortalConfig/current').set({ enabled: true });
  assert.equal((await call({ action: 'bootstrap', includeDocuments: false })).memberships[0].status, 'active');
  const overview = await call({ action: 'overview', providerId: 'legacy' });
  assert.equal(overview.works.length, 1); assert.equal(overview.works[0].payments[0].amount, 25);
  assert.equal(overview.provider.bankAccount_cbu, original.bankAccount_cbu);
  assert.deepEqual((await db.doc('projects/film/areaExpenses/work').get()).data(), work);
  assert.deepEqual(preserved((await db.doc('providers/legacy').get()).data()), preserved(original));
  console.log('PASS real Firestore transactions: read-only preview, version rejection, concurrent idempotence, exact two-document write set, bank/work/payment/membership preservation; natural Google bootstrap activates the same provider without new roles or signup.');
} finally { await db.terminate(); await app.delete(); }
